# Zadanie 2.1 – funkcje wbudowane

max_number = max(7, 5, 6, 3, 8, 2)  # max_number – największa z podanych liczb
print("Max number:", max_number)

min_number = min(4, 7, 2, 3, 9, 8)  # min_number – najmniejsza z podanych liczb
print("Min number:", min_number)

str_length = len("computer science")  # str_length – liczba znaków w tekście
print("Text length:", str_length)

letter = input("Enter a letter: ")  # letter – tekst/litera wpisana z klawiatury
print("Entered letter:", letter)

number = int("20303")  # number – tekst zamieniony na liczbę całkowitą
print("Integer:", number)

binary_number = bin(304)  # binary_number – zapis liczby 304 w systemie binarnym
print("Binary:", binary_number)

hex_number = hex(304)  # hex_number – zapis liczby 304 w systemie szesnastkowym
print("Hexadecimal:", hex_number)

unicode_number = ord("€")  # unicode_number – kod Unicode znaku euro
print("Unicode:", unicode_number)

absolute_number = abs(-17)  # absolute_number – wartość bezwzględna liczby -17
print("Absolute value:", absolute_number)
