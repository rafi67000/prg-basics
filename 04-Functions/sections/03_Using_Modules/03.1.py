# Zadanie 3.1 – wykorzystanie modułu math
import math  # Moduł zawierający funkcje matematyczne

square_root = math.sqrt(7)  # square_root – pierwiastek kwadratowy z 7
print("Square root of 7:", square_root)

logarithm = math.log(5)  # logarithm – logarytm naturalny z 5
print("Natural logarithm of 5:", logarithm)

sine = math.sin(math.radians(90))  # sine – sinus 90 stopni; radians zamienia stopnie na radiany
print("Sine of 90 degrees:", sine)
